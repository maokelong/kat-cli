use std::fmt::Write;

use prost_reflect::EnumDescriptor;

use super::{
    plan::{
        ColumnPlan, ColumnSource, Presence, ProtoField, RelationPlan, RelationSource,
        RelationalPlan, ScalarType, ScalarValue,
    },
    prost_binding::ProstBindings,
};

#[derive(Clone, Copy)]
pub(super) enum CaptureLayout {
    #[cfg(feature = "protobuf-source-contract-fixture")]
    Standalone,
    #[cfg_attr(test, allow(dead_code))]
    ProfilerPayload,
}

pub(super) fn render(
    plan: &RelationalPlan,
    bindings: &ProstBindings,
    capture_layout: CaptureLayout,
) -> String {
    let mut output = String::new();
    writeln!(
        output,
        "// @generated by protobuf_source_codegen; do not edit.\n"
    )
    .expect("writing generated Rust to String cannot fail");

    render_enum_symbol_constants(&mut output, plan);
    render_row_types(&mut output, plan);
    render_capture_layout(&mut output, plan, capture_layout);
    for root in &plan.roots {
        let root_type = bindings.root_type(root.spec_index);
        writeln!(
            output,
            "pub(crate) fn append_{}_root(\n    capture: &mut crate::protobuf_source::SourceTableCapture,\n    parent_row_id: u64,\n    value: &{},\n) -> anyhow::Result<()> {{",
            root.root_table_name, root_type
        )
        .expect("writing generated Rust to String cannot fail");
        let mut renderer = EmitterRenderer {
            output: &mut output,
            plan,
            bindings,
            indent: 1,
        };
        renderer.line("let _ = value;");
        renderer.emit_relation(root.relation_slot, "value", "parent_row_id", None);
        renderer.line("Ok(())");
        writeln!(output, "}}\n").expect("writing generated Rust to String cannot fail");
    }
    output
}

fn render_row_types(output: &mut String, plan: &RelationalPlan) {
    for relation in &plan.relations {
        for (slot, column) in relation.columns.iter().enumerate() {
            render_nested_row_types(output, relation.slot, &[slot], column);
        }
        render_row_type(
            output,
            &format!("ProtobufSourceRelation{}Row", relation.slot),
            &relation.columns,
            true,
        );
    }
}

fn render_nested_row_types(
    output: &mut String,
    relation_slot: usize,
    path: &[usize],
    column: &ColumnPlan,
) {
    let ColumnSource::Struct { fields, .. } = &column.source else {
        return;
    };
    for (slot, field) in fields.iter().enumerate() {
        let mut child_path = path.to_vec();
        child_path.push(slot);
        render_nested_row_types(output, relation_slot, &child_path, field);
    }
    render_row_type(output, &nested_row_type(relation_slot, path), fields, false);
}

fn render_row_type(output: &mut String, name: &str, columns: &[ColumnPlan], top_level: bool) {
    writeln!(output, "#[derive(serde::Serialize)]\nstruct {name}<'a> {{")
        .expect("writing generated Rust to String cannot fail");
    for (slot, column) in columns.iter().enumerate() {
        writeln!(
            output,
            "    #[serde(rename = {})]\n    column_{slot}: {},",
            literal(&column.name),
            render_row_field_type(column, name, slot)
        )
        .expect("writing generated Rust to String cannot fail");
    }
    writeln!(
        output,
        "    #[serde(skip)]\n    marker: std::marker::PhantomData<&'a ()>,\n}}"
    )
    .expect("writing generated Rust to String cannot fail");

    let trait_name = if top_level {
        "EstimatedRow"
    } else {
        "EstimatedValue"
    };
    writeln!(
        output,
        "impl<'a> crate::protobuf_source::{trait_name} for {name}<'a> {{\n    fn estimated_bytes(&self) -> anyhow::Result<usize> {{\n        let mut total = {};",
        if top_level { 0 } else { 1 }
    )
    .expect("writing generated Rust to String cannot fail");
    for slot in 0..columns.len() {
        writeln!(
            output,
            "        crate::protobuf_source::add_estimated_bytes(&mut total, crate::protobuf_source::EstimatedValue::estimated_bytes(&self.column_{slot})?)?;"
        )
        .expect("writing generated Rust to String cannot fail");
    }
    writeln!(output, "        Ok(total)\n    }}")
        .expect("writing generated Rust to String cannot fail");
    if !top_level {
        writeln!(
            output,
            "    fn estimated_null_bytes() -> anyhow::Result<usize> {{\n        let mut total = 1;"
        )
        .expect("writing generated Rust to String cannot fail");
        for (slot, column) in columns.iter().enumerate() {
            let field_type = render_row_field_type(column, name, slot);
            writeln!(
                output,
                "        crate::protobuf_source::add_estimated_bytes(&mut total, <{field_type} as crate::protobuf_source::EstimatedValue>::estimated_null_bytes()?)?;"
            )
            .expect("writing generated Rust to String cannot fail");
        }
        writeln!(output, "        Ok(total)\n    }}")
            .expect("writing generated Rust to String cannot fail");
    }
    writeln!(output, "}}\n").expect("writing generated Rust to String cannot fail");
}

fn render_row_field_type(column: &ColumnPlan, owner: &str, slot: usize) -> String {
    let base = match &column.source {
        ColumnSource::RowId | ColumnSource::ParentRowId | ColumnSource::RepeatedIndex => {
            "u64".to_string()
        }
        ColumnSource::Scalar { scalar, .. } => scalar_rendering(*scalar).rust_type.to_string(),
        ColumnSource::Struct { .. } => {
            let owner = owner
                .strip_suffix("Row")
                .or_else(|| owner.strip_suffix("Struct"))
                .expect("generated row type has a known suffix");
            format!("{owner}Column{slot}Struct<'a>")
        }
    };
    if column.nullable {
        format!("Option<{base}>")
    } else {
        base
    }
}

fn render_scalar_value(scalar: ScalarType, expression: ScalarExpression<'_>) -> String {
    let value = expression.value();
    match scalar_rendering(scalar).access {
        ScalarAccess::Copy => expression.copy_value(),
        ScalarAccess::Utf8 => format!("({value}).as_str()"),
        ScalarAccess::Binary => {
            format!("crate::protobuf_source::BinaryValue::new(({value}).as_slice())")
        }
    }
}

#[derive(Clone, Copy)]
enum ScalarAccess {
    Copy,
    Utf8,
    Binary,
}

impl ScalarAccess {
    fn render_optional(self, scalar: ScalarType, containing_value: &str, field: &str) -> String {
        match self {
            Self::Utf8 => format!("{containing_value}.{field}.as_deref()"),
            Self::Copy | Self::Binary => {
                let expression =
                    render_scalar_value(scalar, ScalarExpression::Borrowed("field_value"));
                format!("{containing_value}.{field}.as_ref().map(|field_value| {expression})")
            }
        }
    }
}

struct ScalarRendering {
    arrow_type: &'static str,
    rust_type: &'static str,
    access: ScalarAccess,
}

fn scalar_rendering(scalar: ScalarType) -> ScalarRendering {
    let (arrow_type, rust_type, access) = match scalar {
        ScalarType::Boolean => (
            "arrow_schema::DataType::Boolean",
            "bool",
            ScalarAccess::Copy,
        ),
        ScalarType::Int32 => ("arrow_schema::DataType::Int32", "i32", ScalarAccess::Copy),
        ScalarType::Int64 => ("arrow_schema::DataType::Int64", "i64", ScalarAccess::Copy),
        ScalarType::UInt32 => ("arrow_schema::DataType::UInt32", "u32", ScalarAccess::Copy),
        ScalarType::UInt64 => ("arrow_schema::DataType::UInt64", "u64", ScalarAccess::Copy),
        ScalarType::Float32 => ("arrow_schema::DataType::Float32", "f32", ScalarAccess::Copy),
        ScalarType::Float64 => ("arrow_schema::DataType::Float64", "f64", ScalarAccess::Copy),
        ScalarType::Utf8 => (
            "arrow_schema::DataType::Utf8",
            "&'a str",
            ScalarAccess::Utf8,
        ),
        ScalarType::Binary => (
            "arrow_schema::DataType::Binary",
            "crate::protobuf_source::BinaryValue<'a>",
            ScalarAccess::Binary,
        ),
    };
    ScalarRendering {
        arrow_type,
        rust_type,
        access,
    }
}

fn nested_row_type(relation_slot: usize, path: &[usize]) -> String {
    let suffix = path
        .iter()
        .map(|slot| format!("Column{slot}"))
        .collect::<String>();
    format!("ProtobufSourceRelation{relation_slot}{suffix}Struct")
}

fn render_enum_symbol_constants(output: &mut String, plan: &RelationalPlan) {
    for (origin_index, origin) in plan.enum_origins.iter().enumerate() {
        writeln!(
            output,
            "const PROTOBUF_ENUM_SYMBOLS_{origin_index}: &[crate::protobuf_source::EnumSymbol] = &["
        )
        .expect("writing generated Rust to String cannot fail");
        for symbol in &origin.symbols {
            writeln!(
                output,
                "    crate::protobuf_source::EnumSymbol::new({}, {}),",
                symbol.number,
                literal(&symbol.symbol)
            )
            .expect("writing generated Rust to String cannot fail");
        }
        writeln!(output, "];\n").expect("writing generated Rust to String cannot fail");
    }
}

fn render_capture_layout(
    output: &mut String,
    plan: &RelationalPlan,
    capture_layout: CaptureLayout,
) {
    let layout_type = match capture_layout {
        #[cfg(feature = "protobuf-source-contract-fixture")]
        CaptureLayout::Standalone => "crate::protobuf_source::SourceTableLayout",
        CaptureLayout::ProfilerPayload => {
            "crate::protobuf_source::profiler_occurrence::ProfilerPayloadLayout"
        }
    };
    writeln!(
        output,
        "pub(crate) fn protobuf_source_layout() -> {layout_type} {{"
    )
    .expect("writing generated Rust to String cannot fail");
    writeln!(output, "    let relations = vec![")
        .expect("writing generated Rust to String cannot fail");
    for relation in &plan.relations {
        writeln!(
            output,
            "        crate::protobuf_source::RelationSpec::new({}, std::sync::Arc::new(arrow_schema::Schema::new(vec![",
            literal(&relation.name)
        )
        .expect("writing generated Rust to String cannot fail");
        for column in &relation.columns {
            writeln!(output, "            {},", render_arrow_field(column))
                .expect("writing generated Rust to String cannot fail");
        }
        writeln!(output, "        ]))),").expect("writing generated Rust to String cannot fail");
    }
    writeln!(output, "    ];").expect("writing generated Rust to String cannot fail");
    writeln!(output, "    let enum_origins = vec![")
        .expect("writing generated Rust to String cannot fail");
    for (origin_index, origin) in plan.enum_origins.iter().enumerate() {
        writeln!(
            output,
            "        crate::protobuf_source::EnumOriginSpec::new(crate::protobuf_source::RelationSlot::new({}), {}, {}, PROTOBUF_ENUM_SYMBOLS_{}),",
            origin.relation_slot,
            literal(&origin.field_path),
            literal(&origin.enum_fqn),
            origin_index
        )
        .expect("writing generated Rust to String cannot fail");
    }
    writeln!(output, "    ];").expect("writing generated Rust to String cannot fail");
    writeln!(
        output,
        "    {layout_type}::from_generated(relations, enum_origins)\n}}\n"
    )
    .expect("writing generated Rust to String cannot fail");
    #[cfg(feature = "protobuf-source-contract-fixture")]
    if matches!(capture_layout, CaptureLayout::Standalone) {
        writeln!(
            output,
            "pub(crate) fn new_protobuf_source_capture(\n    options: crate::protobuf_source::BufferOptions,\n    tables: crate::dataset_writer::DatasetTableFactory,\n) -> anyhow::Result<crate::protobuf_source::SourceTableCapture> {{"
        )
        .expect("writing generated Rust to String cannot fail");
        writeln!(
            output,
            "    protobuf_source_layout().into_capture(options, tables)"
        )
        .expect("writing generated Rust to String cannot fail");
        writeln!(output, "}}\n").expect("writing generated Rust to String cannot fail");
    }
}

pub(super) fn render_enum_symbol_accessor(
    output: &mut String,
    accessor_name: &str,
    enum_def: &EnumDescriptor,
) {
    writeln!(
        output,
        "pub(crate) fn {accessor_name}() -> (&'static str, &'static [crate::protobuf_source::EnumSymbol]) {{"
    )
    .expect("writing generated Rust to String cannot fail");
    writeln!(
        output,
        "    const SYMBOLS: &[crate::protobuf_source::EnumSymbol] = &["
    )
    .expect("writing generated Rust to String cannot fail");
    for symbol in enum_def.values() {
        writeln!(
            output,
            "        crate::protobuf_source::EnumSymbol::new({}, {}),",
            symbol.number(),
            literal(symbol.name())
        )
        .expect("writing generated Rust to String cannot fail");
    }
    writeln!(
        output,
        "    ];\n    ({}, SYMBOLS)\n}}\n",
        literal(enum_def.full_name())
    )
    .expect("writing generated Rust to String cannot fail");
}

fn render_arrow_field(column: &ColumnPlan) -> String {
    format!(
        "arrow_schema::Field::new({}, {}, {})",
        literal(&column.name),
        render_arrow_type(column),
        column.nullable
    )
}

fn render_arrow_type(column: &ColumnPlan) -> String {
    match &column.source {
        ColumnSource::RowId | ColumnSource::ParentRowId | ColumnSource::RepeatedIndex => {
            "arrow_schema::DataType::UInt64".to_string()
        }
        ColumnSource::Scalar { scalar, .. } => scalar_rendering(*scalar).arrow_type.to_string(),
        ColumnSource::Struct { fields, .. } => {
            let fields = fields
                .iter()
                .map(render_arrow_field)
                .collect::<Vec<_>>()
                .join(", ");
            format!("arrow_schema::DataType::Struct(vec![{fields}].into())")
        }
    }
}

struct EmitterRenderer<'a> {
    output: &'a mut String,
    plan: &'a RelationalPlan,
    bindings: &'a ProstBindings,
    indent: usize,
}

impl EmitterRenderer<'_> {
    fn emit_relation(
        &mut self,
        relation_slot: usize,
        value: &str,
        parent_row_id: &str,
        repeated_index: Option<&str>,
    ) {
        let relation = &self.plan.relations[relation_slot];
        let has_row_id = relation
            .columns
            .iter()
            .any(|column| matches!(column.source, ColumnSource::RowId));
        let row_id = format!("row_id_{relation_slot}");
        if has_row_id {
            self.line(&format!(
                "let {row_id} = capture.allocate_row_id(crate::protobuf_source::RelationSlot::new({relation_slot}))?;"
            ));
        }
        self.line(&format!(
            "let row_{relation_slot} = ProtobufSourceRelation{relation_slot}Row {{"
        ));
        self.indent += 1;
        for (column_slot, column) in relation.columns.iter().enumerate() {
            let expression = self.render_column_expression(
                column,
                column_slot,
                relation_slot,
                &[column_slot],
                value,
                parent_row_id,
                repeated_index,
                has_row_id.then_some(row_id.as_str()),
            );
            self.line(&format!("column_{column_slot}: {expression},"));
        }
        self.line("marker: std::marker::PhantomData,");
        self.indent -= 1;
        self.line("};");
        self.line(&format!(
            "capture.append_row(crate::protobuf_source::RelationSlot::new({relation_slot}), &row_{relation_slot})?;"
        ));

        for child in self.child_relations(relation_slot) {
            self.emit_child(child, value, has_row_id.then_some(row_id.as_str()));
        }
    }

    fn emit_child(
        &mut self,
        relation: RelationPlan,
        parent_value: &str,
        parent_row_id: Option<&str>,
    ) {
        let parent_row_id = parent_row_id.expect("a relation with children has a planned row id");
        let slot = relation.slot;
        match &relation.source {
            RelationSource::RepeatedMessage { field, .. }
            | RelationSource::RepeatedValue { field, .. } => {
                let binding = self.bindings.field(field);
                let index = format!("repeated_index_{slot}");
                let value = format!("value_{slot}");
                self.line(&format!(
                    "for ({index}, {value}) in {parent_value}.{}.iter().enumerate() {{",
                    binding.rust_field_ident
                ));
                self.indent += 1;
                self.line(&format!(
                    "let {index} = u64::try_from({index}).map_err(|_| anyhow::anyhow!({}))?;",
                    literal(&format!(
                        "repeated index overflows u64 in relation {}",
                        relation.name
                    ))
                ));
                self.emit_relation(slot, &value, parent_row_id, Some(&index));
                self.indent -= 1;
                self.line("}");
            }
            RelationSource::OptionalMessage { field, .. } => {
                let binding = self.bindings.field(field);
                let value = format!("value_{slot}");
                self.line(&format!(
                    "if let Some({value}) = {parent_value}.{}.as_ref() {{",
                    binding.rust_field_ident
                ));
                self.indent += 1;
                self.emit_relation(slot, &value, parent_row_id, None);
                self.indent -= 1;
                self.line("}");
            }
            RelationSource::OneofMessage { field, .. } => {
                let binding = self.bindings.field(field);
                let oneof = binding
                    .oneof
                    .as_ref()
                    .expect("oneof relation has a oneof prost binding");
                let value = format!("value_{slot}");
                self.line(&format!(
                    "if let Some({}::{}({value})) = {parent_value}.{}.as_ref() {{",
                    oneof.rust_enum_path, oneof.rust_variant_ident, oneof.rust_group_ident
                ));
                self.indent += 1;
                self.emit_relation(slot, &value, parent_row_id, None);
                self.indent -= 1;
                self.line("}");
            }
            RelationSource::Root { .. } => unreachable!("a root relation is not a child"),
        }
    }

    #[allow(clippy::too_many_arguments)]
    fn render_column_expression(
        &self,
        column: &ColumnPlan,
        slot: usize,
        relation_slot: usize,
        path: &[usize],
        value: &str,
        parent_row_id: &str,
        repeated_index: Option<&str>,
        row_id: Option<&str>,
    ) -> String {
        match &column.source {
            ColumnSource::RowId => row_id.expect("planned row id").to_string(),
            ColumnSource::ParentRowId => parent_row_id.to_string(),
            ColumnSource::RepeatedIndex => {
                repeated_index.expect("planned repeated index").to_string()
            }
            ColumnSource::Scalar {
                scalar,
                value: source,
            } => match source {
                ScalarValue::RelationValue => {
                    render_scalar_value(*scalar, ScalarExpression::Borrowed(value))
                }
                ScalarValue::Field(field) => {
                    self.render_field_value(*scalar, column.nullable, value, field)
                }
            },
            ColumnSource::Struct { field, fields } => {
                let binding = self.bindings.field(field);
                let nested_value = format!("struct_value_{}_{}", field.number, slot);
                let type_name = nested_row_type(relation_slot, path);
                let mut members = Vec::new();
                for (nested_slot, nested) in fields.iter().enumerate() {
                    let mut nested_path = path.to_vec();
                    nested_path.push(nested_slot);
                    let expression = self.render_column_expression(
                        nested,
                        nested_slot,
                        relation_slot,
                        &nested_path,
                        &nested_value,
                        "",
                        None,
                        None,
                    );
                    members.push(format!("column_{nested_slot}: {expression}"));
                }
                members.push("marker: std::marker::PhantomData".to_string());
                format!(
                    "{value}.{}.as_ref().map(|{nested_value}| {type_name} {{ {} }})",
                    binding.rust_field_ident,
                    members.join(", ")
                )
            }
        }
    }

    fn render_field_value(
        &self,
        scalar: ScalarType,
        nullable: bool,
        containing_value: &str,
        field: &ProtoField,
    ) -> String {
        let binding = self.bindings.field(field);
        match (&field.presence, &binding.oneof) {
            (Presence::Oneof { .. }, Some(oneof)) => {
                let expression =
                    render_scalar_value(scalar, ScalarExpression::Borrowed("field_value"));
                format!(
                    "match {containing_value}.{}.as_ref() {{ Some({}::{}(field_value)) => Some({expression}), _ => None }}",
                    oneof.rust_group_ident, oneof.rust_enum_path, oneof.rust_variant_ident
                )
            }
            (Presence::Explicit, None) => scalar_rendering(scalar).access.render_optional(
                scalar,
                containing_value,
                &binding.rust_field_ident,
            ),
            (Presence::Implicit, None) => {
                let expression = format!("{containing_value}.{}", binding.rust_field_ident);
                let expression = render_scalar_value(scalar, ScalarExpression::Direct(&expression));
                if nullable {
                    format!("Some({expression})")
                } else {
                    expression
                }
            }
            _ => unreachable!("planner and prost binding disagree about field presence"),
        }
    }

    fn child_relations(&self, parent: usize) -> Vec<RelationPlan> {
        self.plan
            .relations
            .iter()
            .filter(|relation| relation.source.parent() == Some(parent))
            .cloned()
            .collect()
    }

    fn line(&mut self, line: &str) {
        writeln!(self.output, "{}{}", "    ".repeat(self.indent), line)
            .expect("writing generated Rust to String cannot fail");
    }
}

#[derive(Clone, Copy)]
enum ScalarExpression<'a> {
    Direct(&'a str),
    Borrowed(&'a str),
}

impl<'a> ScalarExpression<'a> {
    fn value(self) -> &'a str {
        match self {
            Self::Direct(value) | Self::Borrowed(value) => value,
        }
    }

    fn copy_value(self) -> String {
        match self {
            Self::Direct(value) => value.to_string(),
            Self::Borrowed(value) => format!("*({value})"),
        }
    }
}

fn literal(value: &str) -> String {
    format!("{value:?}")
}
