use std::{env, fmt::Write as _, fs, path::PathBuf};

use prost_types::DescriptorProto;

use crate::proto_codegen::{ProtoMessage, message_type_name, snake_to_upper_camel};

const NATIVE_HOOK_RECORDS_FILE: &str = "native_hook_records.rs";

pub(crate) const NATIVE_HOOK_PROTO_FILES: &[&str] = &[
    "proto/native_hook/native_hook_config.proto",
    "proto/native_hook/native_hook_result.proto",
];
pub(crate) const NATIVE_HOOK_RESULT_PROTO: &str = "proto/native_hook/native_hook_result.proto";

#[derive(Clone, Debug)]
pub(crate) struct NativeHookEventSpec {
    pub(crate) prost_variant: String,
    pub(crate) record_variant: String,
    pub(crate) message_name: String,
    pub(crate) table_name: String,
}

pub(crate) fn native_hook_events_from_descriptor(
    native_hook_data: &DescriptorProto,
    messages: &[ProtoMessage],
) -> Vec<NativeHookEventSpec> {
    let event_oneof_index = native_hook_data
        .oneof_decl
        .iter()
        .position(|oneof| oneof.name.as_deref() == Some("event"))
        .unwrap_or_else(|| {
            panic!("NativeHookData.oneof event should exist in {NATIVE_HOOK_RESULT_PROTO}")
        }) as i32;

    let events = native_hook_data
        .field
        .iter()
        .filter(|field| field.oneof_index == Some(event_oneof_index))
        .map(|field| {
            let field_name = field
                .name
                .as_ref()
                .expect("oneof event field should have a name");
            let message_name = field
                .type_name
                .as_ref()
                .map(|type_name| message_type_name(type_name))
                .expect("oneof event field should have a message type");
            assert!(
                messages.iter().any(|message| message.name == message_name),
                "{message_name} should exist in {NATIVE_HOOK_RESULT_PROTO}"
            );
            NativeHookEventSpec {
                prost_variant: snake_to_upper_camel(field_name),
                record_variant: native_hook_record_variant(&message_name),
                table_name: native_hook_table_name(&message_name),
                message_name,
            }
        })
        .collect::<Vec<_>>();

    assert!(
        !events.is_empty(),
        "NativeHookData.oneof event should contain event fields in {NATIVE_HOOK_RESULT_PROTO}"
    );

    events
}

pub(crate) fn generate_native_hook_records(events: &[NativeHookEventSpec]) -> std::io::Result<()> {
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set"));
    fs::write(
        out_dir.join(NATIVE_HOOK_RECORDS_FILE),
        render_native_hook_records(events),
    )
}

fn render_native_hook_records(events: &[NativeHookEventSpec]) -> String {
    let mut output = String::new();
    output.push_str("// @generated by kat/platform/datasource/build.rs. Do not edit.\n\n");
    output.push_str("use crate::{\n");
    output.push_str("    domains::native_hook::{NativeHookEvent, NativeHookEventContext},\n");
    output.push_str("    proto::{\n");
    output.push_str("        NativeHookConfig,\n");
    output.push_str("        kat::native_hook::{\n");
    output.push_str("            native_hook_data::Event,\n");
    for event in events {
        writeln!(output, "            {},", event.message_name).expect("write to string");
    }
    output.push_str("        },\n");
    output.push_str("    },\n");
    output.push_str("};\n\n");

    output.push_str("#[derive(Clone, Debug)]\n");
    output.push_str("pub(crate) enum NativeHookRecord {\n");
    output.push_str("    Config(Box<NativeHookConfig>),\n");
    for event in events {
        writeln!(
            output,
            "    {}(Box<NativeHookEvent<{}>>),",
            event.record_variant, event.message_name
        )
        .expect("write to string");
    }
    output.push_str("}\n\n");

    output.push_str(
        "pub(crate) fn native_hook_record_from_event(\n\
         \x20   context: NativeHookEventContext,\n\
         \x20   event: Option<Event>,\n\
         ) -> Option<NativeHookRecord> {\n",
    );
    output.push_str("    match event {\n");
    for event in events {
        writeln!(
            output,
            "        Some(Event::{}(event)) => Some(NativeHookRecord::{}(Box::new(\n\
             \x20           NativeHookEvent::new(context, event),\n\
             \x20       ))),",
            event.prost_variant, event.record_variant
        )
        .expect("write to string");
    }
    output.push_str("        None => None,\n");
    output.push_str("    }\n");
    output.push_str("}\n");

    output
}

fn native_hook_record_variant(message_name: &str) -> String {
    native_hook_event_base_name(message_name).to_string()
}

fn native_hook_table_name(message_name: &str) -> String {
    format!(
        "native_hook_{}",
        crate::proto_codegen::camel_to_snake(native_hook_event_base_name(message_name))
    )
}

fn native_hook_event_base_name(message_name: &str) -> &str {
    match message_name {
        "RecordStatisticsEvent" => "Statistics",
        message_name => message_name.strip_suffix("Event").unwrap_or(message_name),
    }
}
