use std::{env, fmt::Write as _, fs, path::PathBuf};

use crate::proto_codegen::ProtoMessage;

const FTRACE_EVENT_TABLE_BUILDERS_FILE: &str = "ftrace_event_table_builders.rs";
const FTRACE_TABLE_SET_NAME: &str = "FtraceTableSet";

pub(crate) const FTRACE_EVENT_FAMILIES: &[EventFamilySpec] = &[EventFamilySpec {
    proto_path: "proto/ftrace_data/sched.proto",
    field_name: "sched",
    tables_name: "SchedEventFamilyTables",
}];

pub(crate) struct EventFamilySpec {
    pub(crate) proto_path: &'static str,
    field_name: &'static str,
    tables_name: &'static str,
}

pub(crate) struct EventFamily<'a> {
    pub(crate) spec: &'a EventFamilySpec,
    pub(crate) messages: Vec<ProtoMessage>,
}

pub(crate) fn generate_ftrace_event_table_builders(
    families: &[EventFamily<'_>],
) -> std::io::Result<()> {
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set"));
    fs::write(
        out_dir.join(FTRACE_EVENT_TABLE_BUILDERS_FILE),
        render_ftrace_event_table_builders(families),
    )
}

fn render_ftrace_event_table_builders(families: &[EventFamily<'_>]) -> String {
    let mut output = String::new();
    output.push_str("// @generated by kat/platform/datasource/build.rs. Do not edit.\n\n");
    output.push_str("use anyhow::Result;\n\n");
    output.push_str("use crate::{\n");
    output.push_str("    domains::ftrace::{FtraceEventRecord, FtraceRecord},\n");
    output.push_str("    proto::kat::hitrace::{\n");
    output.push_str("        ftrace_event,\n");
    for family in families {
        for message in &family.messages {
            writeln!(output, "        {},", message.name).expect("write to string");
        }
    }
    output.push_str("    },\n");
    output.push_str("    sinks::arrow::{EventMeta, FtraceEventTableBuilder},\n");
    output.push_str("    arrow_table::ArrowTable,\n");
    output.push_str("};\n\n");

    render_aggregate_table_builders(&mut output, families);
    for family in families {
        render_event_family_table_builders(&mut output, family);
    }

    output
}

fn render_aggregate_table_builders(output: &mut String, families: &[EventFamily<'_>]) {
    writeln!(output, "pub(crate) struct {} {{", FTRACE_TABLE_SET_NAME).expect("write to string");
    for family in families {
        writeln!(
            output,
            "    {}: {},",
            family.spec.field_name, family.spec.tables_name
        )
        .expect("write to string");
    }
    output.push_str("}\n\n");

    writeln!(output, "impl {} {{", FTRACE_TABLE_SET_NAME).expect("write to string");
    output.push_str("    pub(crate) fn new() -> Result<Self> {\n");
    output.push_str("        Ok(Self {\n");
    for family in families {
        writeln!(
            output,
            "            {}: {}::new()?,",
            family.spec.field_name, family.spec.tables_name
        )
        .expect("write to string");
    }
    output.push_str("        })\n");
    output.push_str("    }\n\n");

    output.push_str(
        "    pub(crate) fn push_record(&mut self, record: FtraceRecord) -> Result<()> {\n",
    );
    output.push_str("        match record {\n");
    output.push_str("            FtraceRecord::Event(event) => self.push_event(*event),\n");
    output.push_str("        }\n");
    output.push_str("    }\n\n");

    output.push_str("    fn push_event(&mut self, record: FtraceEventRecord) -> Result<()> {\n");
    for family in families {
        writeln!(
            output,
            "        self.{}.push_event(&record)?;",
            family.spec.field_name
        )
        .expect("write to string");
    }
    output.push_str("        Ok(())\n");
    output.push_str("    }\n\n");

    output.push_str("    pub(crate) fn into_tables(self) -> Result<Vec<ArrowTable>> {\n");
    output.push_str("        let mut tables = Vec::new();\n");
    for family in families {
        writeln!(
            output,
            "        tables.extend(self.{}.into_tables()?);",
            family.spec.field_name
        )
        .expect("write to string");
    }
    output.push_str("        Ok(tables)\n");
    output.push_str("    }\n");
    output.push('\n');
    output.push_str("    #[allow(dead_code)]\n");
    output.push_str("    pub(crate) fn flush_tables(&mut self) -> Result<Vec<ArrowTable>> {\n");
    output.push_str("        let mut tables = Vec::new();\n");
    for family in families {
        writeln!(
            output,
            "        tables.extend(self.{}.flush_tables()?);",
            family.spec.field_name
        )
        .expect("write to string");
    }
    output.push_str("        Ok(tables)\n");
    output.push_str("    }\n");
    output.push_str("}\n\n");
}

fn render_event_family_table_builders(output: &mut String, family: &EventFamily<'_>) {
    writeln!(output, "pub(crate) struct {} {{", family.spec.tables_name).expect("write to string");
    for message in &family.messages {
        writeln!(
            output,
            "    {}: FtraceEventTableBuilder,",
            message.table_name
        )
        .expect("write to string");
    }
    output.push_str("}\n\n");

    writeln!(output, "impl {} {{", family.spec.tables_name).expect("write to string");
    output.push_str("    pub(crate) fn new() -> Result<Self> {\n");
    output.push_str("        Ok(Self {\n");
    for message in &family.messages {
        writeln!(
            output,
            "            {}: FtraceEventTableBuilder::new::<{}>({:?})?,",
            message.table_name, message.name, message.table_name
        )
        .expect("write to string");
    }
    output.push_str("        })\n");
    output.push_str("    }\n\n");

    output.push_str("    #[allow(clippy::clone_on_copy)]\n");
    output.push_str("    fn push_event(&mut self, record: &FtraceEventRecord) -> Result<()> {\n");
    output.push_str("        let meta = EventMeta::from_record(record);\n");
    output.push_str("        let event = &record.event;\n");
    for message in &family.messages {
        writeln!(
            output,
            "        if let Some(ftrace_event::Event::{}(message)) = event.event.as_ref() {{",
            message.name
        )
        .expect("write to string");
        writeln!(
            output,
            "            self.{}.push(meta.clone(), message.clone())?;",
            message.table_name
        )
        .expect("write to string");
        output.push_str("        }\n");
    }
    output.push_str("\n        Ok(())\n");
    output.push_str("    }\n\n");

    output.push_str("    pub(crate) fn into_tables(self) -> Result<Vec<ArrowTable>> {\n");
    output.push_str("        Ok(vec![\n");
    for message in &family.messages {
        writeln!(
            output,
            "            self.{}.into_table()?,",
            message.table_name
        )
        .expect("write to string");
    }
    output.push_str("        ])\n");
    output.push_str("    }\n");
    output.push('\n');
    output.push_str("    #[allow(dead_code)]\n");
    output.push_str("    pub(crate) fn flush_tables(&mut self) -> Result<Vec<ArrowTable>> {\n");
    output.push_str("        Ok(vec![\n");
    for message in &family.messages {
        writeln!(
            output,
            "            self.{}.flush_table()?,",
            message.table_name
        )
        .expect("write to string");
    }
    output.push_str("        ])\n");
    output.push_str("    }\n");
    output.push_str("}\n");
}
