use std::{
    collections::{BTreeMap, BTreeSet},
    env,
    fmt::Write as _,
    fs,
    path::PathBuf,
};

use crate::{
    fixed_result_domain_codegen::{FixedResultChildTableSpec, FixedResultPluginSpec},
    proto_codegen::camel_to_snake,
};

const FIXED_RESULT_TABLE_BUILDERS_FILE: &str = "fixed_result_table_builders.rs";
const FIXED_RESULT_TABLE_SET_NAME: &str = "FixedResultTableSet";

pub(crate) fn generate_fixed_result_table_builders(
    specs: &[FixedResultPluginSpec],
    child_tables: &[FixedResultChildTableSpec],
) -> std::io::Result<()> {
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set"));
    fs::write(
        out_dir.join(FIXED_RESULT_TABLE_BUILDERS_FILE),
        render_table_builders(specs, child_tables),
    )
}

fn render_table_builders(
    specs: &[FixedResultPluginSpec],
    child_tables: &[FixedResultChildTableSpec],
) -> String {
    let mut output = String::new();
    output.push_str("// @generated by crates/kat-rs-datasource/build.rs. Do not edit.\n\n");
    output.push_str("use anyhow::Result;\n\n");
    output.push_str("use crate::{\n");
    output.push_str("    arrow_table::ArrowTable,\n");
    output.push_str("    domains::fixed_result::{FixedResultChildMeta, FixedResultMessage, FixedResultRecord},\n");
    output.push_str("    proto::kat::{\n");
    for (module_name, messages) in grouped_proto_imports(specs, child_tables) {
        writeln!(
            output,
            "        {}::{{{}}},",
            module_name,
            messages.into_iter().collect::<Vec<_>>().join(", ")
        )
        .expect("write to string");
    }
    output.push_str("    },\n");
    output.push_str(
        "    sinks::arrow::{FixedResultChildTableBuilder, FixedResultMessageTableBuilder},\n",
    );
    output.push_str("};\n\n");

    writeln!(output, "pub(crate) struct {FIXED_RESULT_TABLE_SET_NAME} {{")
        .expect("write to string");
    for spec in specs {
        writeln!(
            output,
            "    {}: FixedResultMessageTableBuilder,",
            camel_to_snake(spec.config_message)
        )
        .expect("write to string");
        writeln!(
            output,
            "    {}: FixedResultMessageTableBuilder,",
            camel_to_snake(spec.result_message)
        )
        .expect("write to string");
    }
    for child in child_tables {
        writeln!(
            output,
            "    {}: FixedResultChildTableBuilder,",
            child_field_name(child)
        )
        .expect("write to string");
    }
    output.push_str("}\n\n");

    writeln!(output, "impl {FIXED_RESULT_TABLE_SET_NAME} {{").expect("write to string");
    output.push_str("    pub(crate) fn new() -> Result<Self> {\n");
    output.push_str("        Ok(Self {\n");
    for spec in specs {
        writeln!(
            output,
            "            {}: FixedResultMessageTableBuilder::new::<{}>({:?})?,",
            camel_to_snake(spec.config_message),
            spec.config_message,
            spec.config_table
        )
        .expect("write to string");
        writeln!(
            output,
            "            {}: FixedResultMessageTableBuilder::new::<{}>({:?})?,",
            camel_to_snake(spec.result_message),
            spec.result_message,
            spec.result_table
        )
        .expect("write to string");
    }
    for child in child_tables {
        writeln!(
            output,
            "            {}: FixedResultChildTableBuilder::new::<{}>({:?})?,",
            child_field_name(child),
            child.child_message,
            child.table_name
        )
        .expect("write to string");
    }
    output.push_str("        })\n");
    output.push_str("    }\n\n");

    output.push_str(
        "    pub(crate) fn push_record(&mut self, record: FixedResultRecord) -> Result<()> {\n",
    );
    output.push_str("        match record {\n");
    for spec in specs {
        writeln!(
            output,
            "            FixedResultRecord::{}(record) => self.{}.push(*record)?,",
            spec.config_variant(),
            camel_to_snake(spec.config_message)
        )
        .expect("write to string");
        render_result_push_arm(&mut output, spec, child_tables);
    }
    output.push_str("        }\n\n");
    output.push_str("        Ok(())\n");
    output.push_str("    }\n\n");

    output.push_str("    pub(crate) fn into_tables(self) -> Result<Vec<ArrowTable>> {\n");
    output.push_str("        Ok(vec![\n");
    for spec in specs {
        writeln!(
            output,
            "            self.{}.into_table()?,",
            camel_to_snake(spec.config_message)
        )
        .expect("write to string");
        writeln!(
            output,
            "            self.{}.into_table()?,",
            camel_to_snake(spec.result_message)
        )
        .expect("write to string");
    }
    for child in child_tables {
        writeln!(
            output,
            "            self.{}.into_table()?,",
            child_field_name(child)
        )
        .expect("write to string");
    }
    output.push_str("        ])\n");
    output.push_str("    }\n\n");

    output.push_str("    #[allow(dead_code)]\n");
    output.push_str("    pub(crate) fn flush_tables(&mut self) -> Result<Vec<ArrowTable>> {\n");
    output.push_str("        Ok(vec![\n");
    for spec in specs {
        writeln!(
            output,
            "            self.{}.flush_table()?,",
            camel_to_snake(spec.config_message)
        )
        .expect("write to string");
        writeln!(
            output,
            "            self.{}.flush_table()?,",
            camel_to_snake(spec.result_message)
        )
        .expect("write to string");
    }
    for child in child_tables {
        writeln!(
            output,
            "            self.{}.flush_table()?,",
            child_field_name(child)
        )
        .expect("write to string");
    }
    output.push_str("        ])\n");
    output.push_str("    }\n");
    output.push_str("}\n");

    output
}

fn grouped_proto_imports(
    specs: &[FixedResultPluginSpec],
    child_tables: &[FixedResultChildTableSpec],
) -> BTreeMap<String, BTreeSet<String>> {
    let mut imports = BTreeMap::<String, BTreeSet<String>>::new();

    for spec in specs {
        let messages = imports.entry(spec.module_name.to_string()).or_default();
        messages.insert(spec.config_message.to_string());
        messages.insert(spec.result_message.to_string());
    }

    for child in child_tables {
        imports
            .entry(child.module_name.clone())
            .or_default()
            .insert(child.child_message.clone());
    }

    imports
}

fn render_result_push_arm(
    output: &mut String,
    spec: &FixedResultPluginSpec,
    child_tables: &[FixedResultChildTableSpec],
) {
    let children = child_tables
        .iter()
        .filter(|child| child.parent_variant == spec.result_variant())
        .collect::<Vec<_>>();

    if children.is_empty() {
        writeln!(
            output,
            "            FixedResultRecord::{}(record) => self.{}.push(*record)?,",
            spec.result_variant(),
            camel_to_snake(spec.result_message)
        )
        .expect("write to string");
        return;
    }

    writeln!(
        output,
        "            FixedResultRecord::{}(record) => {{",
        spec.result_variant()
    )
    .expect("write to string");
    output.push_str("                let record = *record;\n");
    output.push_str("                let meta = record.meta;\n");
    output.push_str("                let message = record.message;\n");
    writeln!(
        output,
        "                self.{}.push(FixedResultMessage::new(meta.clone(), message.clone()))?;",
        camel_to_snake(spec.result_message)
    )
    .expect("write to string");
    for child in children {
        writeln!(
            output,
            "                for (child_index, child) in message.{}.into_iter().enumerate() {{",
            child.field_name
        )
        .expect("write to string");
        writeln!(
            output,
            "                    self.{}.push(FixedResultChildMeta::new(meta.clone(), child_index as u32), child)?;",
            child_field_name(child)
        )
        .expect("write to string");
        output.push_str("                }\n");
    }
    output.push_str("            }\n");
}

fn child_field_name(child: &FixedResultChildTableSpec) -> String {
    child.table_name.clone()
}
