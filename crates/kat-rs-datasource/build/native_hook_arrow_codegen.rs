use std::{env, fmt::Write as _, fs, path::PathBuf};

use crate::{native_hook_domain_codegen::NativeHookEventSpec, proto_codegen::camel_to_snake};

const NATIVE_HOOK_TABLE_BUILDERS_FILE: &str = "native_hook_table_builders.rs";
const NATIVE_HOOK_TABLE_SET_NAME: &str = "NativeHookTableSet";

pub(crate) fn generate_native_hook_table_builders(
    events: &[NativeHookEventSpec],
) -> std::io::Result<()> {
    let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set"));
    fs::write(
        out_dir.join(NATIVE_HOOK_TABLE_BUILDERS_FILE),
        render_native_hook_table_builders(events),
    )
}

fn render_native_hook_table_builders(events: &[NativeHookEventSpec]) -> String {
    let mut output = String::new();
    output.push_str("// @generated by crates/kat-rs-datasource/build.rs. Do not edit.\n\n");
    output.push_str("use anyhow::Result;\n\n");
    output.push_str("use crate::{\n");
    output.push_str("    domains::native_hook::NativeHookRecord,\n");
    output.push_str("    proto::{\n");
    output.push_str("        NativeHookConfig,\n");
    output.push_str("        kat::native_hook::{\n");
    for event in events {
        writeln!(output, "            {},", event.message_name).expect("write to string");
    }
    output.push_str("        },\n");
    output.push_str("    },\n");
    output.push_str("    sinks::arrow::{MessageTableBuilder, NativeHookEventTableBuilder},\n");
    output.push_str("    arrow_table::ArrowTable,\n");
    output.push_str("};\n\n");

    writeln!(
        output,
        "pub(crate) struct {} {{",
        NATIVE_HOOK_TABLE_SET_NAME
    )
    .expect("write to string");
    output.push_str("    config: MessageTableBuilder<NativeHookConfig>,\n");
    for event in events {
        writeln!(
            output,
            "    {}: NativeHookEventTableBuilder,",
            camel_to_snake(&event.record_variant)
        )
        .expect("write to string");
    }
    output.push_str("}\n\n");

    writeln!(output, "impl {} {{", NATIVE_HOOK_TABLE_SET_NAME).expect("write to string");
    output.push_str("    pub(crate) fn new() -> Result<Self> {\n");
    output.push_str("        Ok(Self {\n");
    output.push_str("            config: MessageTableBuilder::new(\"native_hook_config\")?,\n");
    for event in events {
        writeln!(
            output,
            "            {}: NativeHookEventTableBuilder::new::<{}>({:?})?,",
            camel_to_snake(&event.record_variant),
            event.message_name,
            event.table_name
        )
        .expect("write to string");
    }
    output.push_str("        })\n");
    output.push_str("    }\n\n");

    output.push_str(
        "    pub(crate) fn push_record(&mut self, record: NativeHookRecord) -> Result<()> {\n",
    );
    output.push_str("        match record {\n");
    output
        .push_str("            NativeHookRecord::Config(config) => self.config.push(*config)?,\n");
    for event in events {
        writeln!(
            output,
            "            NativeHookRecord::{}(record) => self.{}.push(*record)?,",
            event.record_variant,
            camel_to_snake(&event.record_variant)
        )
        .expect("write to string");
    }
    output.push_str("        }\n\n");
    output.push_str("        Ok(())\n");
    output.push_str("    }\n\n");

    output.push_str("    pub(crate) fn into_tables(self) -> Result<Vec<ArrowTable>> {\n");
    output.push_str("        Ok(vec![\n");
    output.push_str("            self.config.into_table()?,\n");
    for event in events {
        writeln!(
            output,
            "            self.{}.into_table()?,",
            camel_to_snake(&event.record_variant)
        )
        .expect("write to string");
    }
    output.push_str("        ])\n");
    output.push_str("    }\n");
    output.push('\n');
    output.push_str("    #[allow(dead_code)]\n");
    output.push_str("    pub(crate) fn flush_tables(&mut self) -> Result<Vec<ArrowTable>> {\n");
    output.push_str("        Ok(vec![\n");
    output.push_str("            self.config.flush_table()?,\n");
    for event in events {
        writeln!(
            output,
            "            self.{}.flush_table()?,",
            camel_to_snake(&event.record_variant)
        )
        .expect("write to string");
    }
    output.push_str("        ])\n");
    output.push_str("    }\n");
    output.push_str("}\n");

    output
}
