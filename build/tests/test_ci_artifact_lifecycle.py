def upload_blocks(workflow: str) -> list[str]:
    blocks: list[str] = []
    lines = workflow.splitlines()
    for index, line in enumerate(lines):
        if f"uses: {UPLOAD_ARTIFACT_ACTION}" not in line:
            continue
        end = index + 1
        while end < len(lines) and not lines[end].startswith("      - name:"):
            end += 1
        blocks.append("\n".join(lines[index:end]))
    return blocks


class CiArtifactLifecycleTests(unittest.TestCase):
    def test_release_workflow_is_generated_once_for_kat_namespace(self) -> None:
        config = tomllib.loads(DIST_WORKSPACE.read_text(encoding="utf-8"))
        dist = config["dist"]
        self.assertEqual(dist["tag-namespace"], "kat")
        self.assertEqual(dist["pr-run-mode"], "plan")
        self.assertNotIn("plan-jobs", dist)
        self.assertEqual(dist["local-artifacts-jobs"], ["./build-payloads-ci"])
        self.assertTrue(RELEASE_WORKFLOW.is_file())
        self.assertFalse(LEGACY_RELEASE_WORKFLOW.exists())

        generated = [
            path
            for path in (REPOSITORY / ".github/workflows").glob("*.yml")
            if path.read_text(encoding="utf-8").startswith(
                "# This file was autogenerated by dist:"
            )
        ]
        self.assertEqual(generated, [RELEASE_WORKFLOW])

        release_creators = [
            path
            for path in (REPOSITORY / ".github/workflows").glob("*.yml")
            if "gh release create " in path.read_text(encoding="utf-8")
        ]
        self.assertEqual(release_creators, [RELEASE_WORKFLOW])

        workflow = RELEASE_WORKFLOW.read_text(encoding="utf-8")
        self.assertIn("name: Release", workflow)
        self.assertIn("  pull_request:", workflow)
        self.assertIn("      - 'kat**[0-9]+.[0-9]+.[0-9]+*'", workflow)
        self.assertNotIn("      - '**[0-9]+.[0-9]+.[0-9]+*'", workflow)
        self.assertIn("  custom-build-payloads-ci:", workflow)
        self.assertIn("uses: ./.github/workflows/build-payloads-ci.yml", workflow)

    def test_release_dag_uses_the_verified_channel_and_terminal_finalizer(self) -> None:
        workflow = RELEASE_WORKFLOW.read_text(encoding="utf-8")

        self.assertIn(
            "needs.plan.outputs.publishing == 'true' || "
            "fromJson(needs.plan.outputs.val).ci.github.pr_run_mode == 'upload'",
            workflow,
        )
        self.assertIn(
            "  build-global-artifacts:\n"
            "    needs:\n"
            "      - plan\n"
            "      - custom-build-payloads-ci\n",
            workflow,
        )
        self.assertIn(
            "  custom-payload-ci:\n"
            "    needs:\n"
            "      - plan\n"
            "      - custom-build-payloads-ci\n",
            workflow,
        )
        self.assertIn(
            "  host:\n"
            "    needs:\n"
            "      - plan\n"
            "      - custom-build-payloads-ci\n"
            "      - build-global-artifacts\n"
            "      - custom-payload-ci\n",
            workflow,
        )
        self.assertIn(
            "needs.custom-build-payloads-ci.result == 'skipped' || "
            "needs.custom-build-payloads-ci.result == 'success'",
            workflow,
        )
        self.assertIn("dist host ${{ needs.plan.outputs.tag-flag }}", workflow)
        self.assertIn(
            'PRERELEASE_FLAG: "${{ '
            "fromJson(steps.host.outputs.manifest).announcement_is_prerelease "
            "&& '--prerelease' || '' }}\"",
            workflow,
        )
        self.assertIn(
            "gh release create \"${{ needs.plan.outputs.tag }}\" "
            '--target "$RELEASE_COMMIT" $PRERELEASE_FLAG',
            workflow,
        )
        self.assertNotIn(
            "fromJson(needs.plan.outputs.val).announcement_is_prerelease",
            workflow,
        )
        self.assertIn(
            "  announce:\n"
            "    needs:\n"
            "      - plan\n"
            "      - host\n",
            workflow,
        )
        terminal_finalizer = (
            "  custom-finalize-release-assets:\n"
            "    needs:\n"
            "      - plan\n"
            "      - announce\n"
            "    uses: ./.github/workflows/finalize-release-assets.yml\n"
            "    with:\n"
            "      plan: ${{ needs.plan.outputs.val }}\n"
            "    secrets: inherit"
        )
        self.assertTrue(workflow.rstrip().endswith(terminal_finalizer))
        self.assertEqual(workflow.count("  custom-finalize-release-assets:"), 1)

        self.assertNotIn("custom-prepare-payload-ci", workflow)
        self.assertNotIn("custom-build-linux-payload-ci", workflow)
        self.assertNotIn("custom-build-windows-payload-ci", workflow)

    def test_channel_and_finalizer_enforce_the_release_state_contract(self) -> None:
        workflow = RELEASE_WORKFLOW.read_text(encoding="utf-8")
        orchestrator = PAYLOAD_ORCHESTRATOR.read_text(encoding="utf-8")
        self.assertIn("  release-channel:", orchestrator)
        self.assertIn("KAT_RELEASE_CHECKOUT_SHA=${actual_checkout}", orchestrator)
        self.assertIn("KAT_RELEASE_CHECKOUT_TREE=${actual_tree}", orchestrator)
        self.assertIn('expected_tag="kat/${version}"', orchestrator)
        self.assertIn(".announcement_tag", orchestrator)
        self.assertIn(
            "python -I -B build/verify_release_versions.py --tag",
            orchestrator,
        )
        self.assertIn("plan-stage manifest 只提供早期信号", orchestrator)
        self.assertIn("needs: release-channel", orchestrator)
        self.assertEqual(orchestrator.count("      - release-channel"), 3)
        self.assertEqual(orchestrator.count("      - prepare"), 2)
        self.assertEqual(
            orchestrator.count(
                "app-version: ${{ "
                "needs.release-channel.outputs['app-version'] }}"
            ),
            1,
        )

        finalizer = FINALIZER_WORKFLOW.read_text(encoding="utf-8")
        self.assertEqual(finalizer.count("  finalize-release-assets:"), 1)
        self.assertIn('permissions:\n  "contents": "write"', workflow)
        self.assertIn("permissions:\n  contents: write", finalizer)
        self.assertIn('expected_tag="kat/${version}"', finalizer)
        self.assertIn(".announcement_tag", finalizer)
        self.assertIn(".announcement_is_prerelease", finalizer)
        self.assertIn("--json tagName,isDraft,isImmutable,isPrerelease", finalizer)
        self.assertIn("and .isDraft == false", finalizer)
        self.assertIn("and .isImmutable == false", finalizer)
        self.assertIn("and .isPrerelease == $expected_prerelease", finalizer)
        self.assertIn("- name: Quarantine a failed Release", finalizer)
        self.assertIn("if: ${{ failure() && !cancelled() }}", finalizer)
        self.assertIn("--json databaseId,tagName", finalizer)
        self.assertIn("releases/${release_id}", finalizer)
        self.assertIn(
            '{draft: true, prerelease: true, make_latest: "false"}',
            finalizer,
        )
        self.assertIn("--input -", finalizer)

